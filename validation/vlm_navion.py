"""Optional: the Navion wing through the vortex-lattice solver of aerodynamics-from-scratch.

Run with
``uv run --with "aero @ git+https://github.com/GMCavalheri/aerodynamics-from-scratch"
python validation/vlm_navion.py``. Without the ``aero`` package it explains how and exits.
Writes ``validation/results/vlm_navion.md``.

The planform is a straight-tapered, unswept wing whose span, area and mean chord are Teper's
(Table X-A): b = 33.4 ft, S = 180 ft^2, cbar = 5.7 ft. For a straight taper,
cbar = (2/3) c_r (1 + l + l^2) / (1 + l) and S = b c_r (1 + l) / 2, which fixes the taper
ratio l = 0.413. The planform shape (straight taper, no sweep) is an assumption; nothing else
is. The comparison is with whole-aircraft data, so it shows what the wing alone contributes.
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
from scipy.optimize import brentq

sys.path.insert(0, str(Path(__file__).resolve().parent))

from flightdyn.aero_derivatives import body_axis_coefficients  # noqa: E402
from flightdyn.trade_studies import neutral_point_shift  # noqa: E402

from reference import navion  # noqa: E402
from reference_aircraft import navion as navion_aircraft  # noqa: E402

RESULTS = Path(__file__).resolve().parent / "results"


def planform(b: float, S: float, cbar: float) -> tuple[float, float]:
    """Root chord and taper ratio of the straight-tapered wing with this b, S and cbar."""

    def mac_error(lam):
        cr = 2 * S / (b * (1 + lam))
        return 2 / 3 * cr * (1 + lam + lam**2) / (1 + lam) - cbar

    lam = brentq(mac_error, 0.05, 1.0)
    return 2 * S / (b * (1 + lam)), lam


def main() -> int:
    try:
        from aero.vortex_lattice_3d import Wing, solve_vlm
    except ImportError:
        print(__doc__.split("Writes")[0])
        print("The optional `aero` package is not installed: nothing to do.")
        return 0
    n = navion()
    b, S, cbar = n["b"], n["S"], n["c"]
    cr, lam = planform(b, S, cbar)
    AR = b * b / S
    wing = Wing.tapered(aspect_ratio=AR, taper=lam, root_chord=cr, name="Navion wing")
    a1, a2 = np.radians(0.0), np.radians(2.0)
    s1, s2 = solve_vlm(wing, a1), solve_vlm(wing, a2)
    CLa = (s2.CL - s1.CL) / (a2 - a1)
    dCm_dCL = (s2.Cm - s1.Cm) / (s2.CL - s1.CL)
    # moments are about x = 0, the quarter-chord line of an unswept wing, so also the MAC's
    # quarter chord: the aerodynamic centre is at 0.25 - dCm/dCL of the MAC
    h_ac = 0.25 - dCm_dCL
    ac = navion_aircraft()
    h_n = n["cg"] / 100 + neutral_point_shift(ac)
    CNa = body_axis_coefficients(ac.aero).CN_a
    lines = [
        "# Navion wing: vortex lattice (aerodynamics-from-scratch) vs whole-aircraft data",
        "",
        "Generated by `validation/vlm_navion.py` with the AERO-01 `aero` package.",
        "",
        f"Planform from Teper Table X-A: b = {b} ft, S = {S} ft², c̄ = {cbar} ft → AR = {AR:.3f},",
        f"straight taper λ = {lam:.3f}, root chord {cr:.2f} ft (unswept: assumed).",
        "",
        "| Quantity | wing alone, VLM | whole aircraft, Teper |",
        "|---|---|---|",
        f"| lift-curve slope [1/rad] | {CLa:.3f} | {n['CL_a']:.2f} (C_Lα), {CNa:.2f} (C_Nα) |",
        f"| aerodynamic centre / neutral point [MAC] | {h_ac:.3f} | {h_n:.3f} (stick-fixed NP) |",
        "",
        f"The wing alone gives {100 * CLa / n['CL_a']:.0f} % of the aircraft's lift slope: the",
        "horizontal tail adds lift slope and the fuselage and downwash take some away. The tail",
        "moves the neutral point",
        f"aft of the wing's aerodynamic centre by {h_n - h_ac:.2f} MAC, the stabilising",
        "contribution that the trade studies vary.",
        "",
    ]
    RESULTS.mkdir(exist_ok=True)
    (RESULTS / "vlm_navion.md").write_text("\n".join(lines))
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
