"""Nondimensional -> dimensional derivatives, checked against the reports' own tables.

Run with ``uv run python validation/derivative_validation.py``. Writes
``validation/results/derivative_validation.md`` and ``docs/figures/derivatives_b747.png``.

Boeing 747 (NASA CR-2144): Tables IX-1/IX-2 (nondimensional) with Table IX-3 (mass, flight
condition) through the Appendix A formulas, against Tables IX-4 and IX-8. Navion (Teper 1969):
Tables X-A to X-C against Tables X-D and X-E.
"""

from __future__ import annotations

import sys
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))

from flightdyn import plotting as P  # noqa: E402
from flightdyn.aero_derivatives import dimensional_derivatives  # noqa: E402
from flightdyn.atmosphere import isa  # noqa: E402
from flightdyn.units import FT, SLUG_FT3  # noqa: E402

from reference import b747 as b747_data  # noqa: E402
from reference import navion as navion_data  # noqa: E402
from reference_aircraft import b747, b747_condition, navion, navion_condition  # noqa: E402

RESULTS = Path(__file__).resolve().parent / "results"

# (report mnemonic, model attribute, factor from SI to the report's ft-based unit)
B747_LON = [
    ("XW", "Xw", 1),
    ("ZW", "Zw", 1),
    ("ZWD", "Zwdot", 1),
    ("ZQ", "Zq", 1 / FT),
    ("MW", "Mw", FT),
    ("MWD", "Mwdot", FT),
    ("MQ", "Mq", 1),
    ("XDE", "Xde", 1 / FT),
    ("ZDE", "Zde", 1 / FT),
    ("MDE", "Mde", 1),
    ("XU*", "Xu", 1),
    ("ZU*", "Zu", 1),
    ("MU*", "Mu", FT),
]
B747_LAT = [
    ("YV", "Yv", 1),
    ("Y*DR", "Ystar_dr", 1),
    ("LB'", "Lb_p", 1),
    ("NB'", "Nb_p", 1),
    ("LP'", "Lp_p", 1),
    ("NP'", "Np_p", 1),
    ("LR'", "Lr_p", 1),
    ("NR'", "Nr_p", 1),
    ("L'DA", "Lda_p", 1),
    ("N'DA", "Nda_p", 1),
    ("L'DR", "Ldr_p", 1),
    ("N'DR", "Ndr_p", 1),
]
NAVION = [
    ("Xu", "Xu", 1),
    ("Xw", "Xw", 1),
    ("Zu", "Zu", 1),
    ("Zw", "Zw", 1),
    ("Zde", "Zde", 1 / FT),
    ("Mw", "Mw", FT),
    ("Mwdot", "Mwdot", FT),
    ("Mq", "Mq", 1),
    ("Yv", "Yv", 1),
    ("Y*dr", "Ystar_dr", 1),
    ("L'b", "Lb_p", 1),
    ("L'p", "Lp_p", 1),
    ("L'r", "Lr_p", 1),
    ("L'da", "Lda_p", 1),
    ("L'dr", "Ldr_p", 1),
    ("N'b", "Nb_p", 1),
    ("N'p", "Np_p", 1),
    ("N'r", "Nr_p", 1),
    ("N'da", "Nda_p", 1),
    ("N'dr", "Ndr_p", 1),
]
NOTES = {"ZQ": "table uses U0 where the force model gives V (cos α0)"}


def b747_dimensional(fc: int, axes: str = "stability"):
    ac, cond = b747(fc, axes), b747_condition(fc)
    rho = float(isa(cond["h"], geopotential=True).rho)
    return dimensional_derivatives(ac.aero, ac.geometry, ac.mass, rho, cond["V"])


def b747_comparison():
    rows = []
    for fc in (1, 2):
        ref = b747_data(fc)
        stab, body = b747_dimensional(fc), b747_dimensional(fc, "body")
        for key, attr, k in B747_LON + B747_LAT:
            r = ref[key]
            lateral = (key, attr, k) in B747_LAT
            rows.append(
                dict(
                    fc=fc,
                    key=key,
                    ref=r,
                    model=getattr(stab, attr) * k,
                    body=getattr(body, attr) * k if lateral else None,
                )
            )
    return rows


def navion_comparison():
    n, ac, c = navion_data(), navion(), navion_condition()
    dd = dimensional_derivatives(ac.aero, ac.geometry, ac.mass, n["rho"] * SLUG_FT3, c["V"])
    return [dict(key=key, ref=n[key], model=getattr(dd, a) * k) for key, a, k in NAVION]


def pct(model, ref):
    return 100.0 * (model / ref - 1.0)


def write_results(b, nv):
    lines = [
        "# Dimensional derivatives from the nondimensional data",
        "",
        "Generated by `validation/derivative_validation.py`. Model = Appendix A formulas applied",
        "to the report's nondimensional derivatives and flight condition; reference = the report's",
        "own dimensional-derivative table. Report units (ft, s, rad).",
        "",
        "## Boeing 747 (NASA CR-2144, Tables IX-1/IX-2 + IX-3 → IX-4, IX-8)",
        "",
        "| Derivative | fc | CR-2144 | model | difference | lateral read as body-axis |",
        "|---|---|---|---|---|---|",
    ]
    for r in b:
        body = f"{pct(r['body'], r['ref']):+.1f} %" if r["body"] is not None else ""
        note = f" ({NOTES[r['key']]})" if r["key"] in NOTES else ""
        lines.append(
            f"| {r['key']} | {r['fc']} | {r['ref']:.4g} | {r['model']:.4g} | "
            f"{pct(r['model'], r['ref']):+.2f} %{note} | {body} |"
        )
    worst = max(abs(pct(r["model"], r["ref"])) for r in b if r["key"] not in NOTES)
    lines += [
        "",
        f"Worst agreement outside the noted derivative: {worst:.2f} %.",
        "",
        "M_u* and M_w agree because the model's aerodynamic Cm0 at the reference balances the",
        "published thrust moment, Cm0 = −T l_th / (q S c̄) (−0.096 at fc 1, −0.037 at fc 2;",
        "`validation/reference_aircraft.py`). With Cm0 = 0, M_u* is 1.6–3× too large and M_w",
        "1.7 % off: the report's derivatives were evaluated with the thrust moment trimmed out.",
        "",
        "## Navion (Teper 1969, Tables X-A to X-C → X-D, X-E)",
        "",
        "| Derivative | Teper | model | Teper / model |",
        "|---|---|---|---|",
    ]
    for r in nv:
        lines.append(
            f"| {r['key']} | {r['ref']:.5g} | {r['model']:.5g} | {r['ref'] / r['model']:.4f} |"
        )
    lines += [
        "",
        "Every ratio is 1.0222 = 184/180 for moments and 1.0231 for forces (the extra 0.08 % is",
        "the printed mass 85.4 slug against W/g = 85.47): Table X-D was computed with",
        "S = 184 ft², while Table X-A prints 180 ft². (M_de is not listed: the model's Cm_de is",
        "derived from it, Table X-B printing none.)",
        "",
    ]
    RESULTS.mkdir(exist_ok=True)
    (RESULTS / "derivative_validation.md").write_text("\n".join(lines))


def figure(b):
    fig, axes = plt.subplots(1, 2, figsize=(11, 5.6), sharex=False)
    for ax, fc in zip(axes, (1, 2), strict=True):
        rs = [r for r in b if r["fc"] == fc]
        y = np.arange(len(rs))[::-1]
        ax.axvspan(-1, 1, color=P.GRID, alpha=0.6, lw=0, label="±1 %  (3-figure rounding)")
        ax.axvline(0, color=P.TEXT_MUTED, lw=0.8)
        body = [(yy, pct(r["body"], r["ref"])) for yy, r in zip(y, rs, strict=True) if r["body"]]
        ax.scatter(
            [np.clip(v, -9.5, 9.5) for _, v in body],
            [yy for yy, _ in body],
            marker="x",
            color=P.SERIES[1],
            label="lateral data read as body-axis",
            zorder=3,
        )
        ax.scatter(
            [np.clip(pct(r["model"], r["ref"]), -9.5, 9.5) for r in rs],
            y,
            color=P.SERIES[0],
            label="model (stability-axis lateral data)",
            zorder=4,
        )
        ax.set_yticks(y, [r["key"] for r in rs])
        ax.set_xlim(-10, 10)
        ax.set_xlabel("model vs CR-2144 table [%]  (clipped at ±9.5)")
        ax.set_title(f"Boeing 747, flight condition {fc}")
        ax.grid(axis="y", visible=False)
    handles, labels = axes[0].get_legend_handles_labels()
    fig.legend(handles, labels, loc="lower center", ncol=3, bbox_to_anchor=(0.5, -0.04))
    P.save(fig, "derivatives_b747.png")


if __name__ == "__main__":
    P.use_style()
    b, nv = b747_comparison(), navion_comparison()
    write_results(b, nv)
    figure(b)
    print((RESULTS / "derivative_validation.md").read_text())
